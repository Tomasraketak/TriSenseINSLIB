#!/bin/sh
#
# Re-vendors INSLIB (and its KFCore submodule) into src/inslib/ and regenerates
# the one-line translation-unit wrappers in src/.
#
#     tools/update_inslib.sh            # the pinned version below
#     tools/update_inslib.sh v1.5.0     # a newer release
#
# Afterwards: build the examples, run tests/host, update the version in
# README.md, and commit src/inslib/ together with the wrappers.
#
# WHY THE SOURCES ARE RENAMED
# ---------------------------
# The Arduino build compiles every .c/.cpp under a library's src/ folder,
# recursively, and offers no way to pass -D flags to a library. INSLIB and
# KFCore size their arrays from -D flags (INS_UNKNOWNS_MAX, ...), and those
# decide whether the filter fits on an 8 KB stack at all.
#
# So the INSLIB/KFCore .c files are stored as .c.inc - byte-for-byte the
# upstream file, only the name differs, so Arduino does not compile them on
# their own - and each one is compiled through a wrapper src/inslib_tu_<name>.c
# that includes src/trisense_inslib_config.h first. Headers keep their names.
# Every #include in INSLIB and KFCore is an unqualified quoted name, so with
# both trees flattened into one folder each include resolves next to its
# includer and no -I flag is needed.
#
# Nothing in INSLIB is patched. VERSIONS.txt records the upstream commits and
# a sha256 of every vendored file so that can be checked.
#
set -eu

INSLIB_REF=${1:-v1.4.2}
INSLIB_URL=${INSLIB_URL:-https://github.com/jnz/INSLIB.git}

HERE=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
DEST="$HERE/src/inslib"
WRAPDIR="$HERE/src"

command -v git >/dev/null 2>&1 || { echo "update_inslib: git is required" >&2; exit 1; }
if command -v sha256sum >/dev/null 2>&1; then SHA="sha256sum"; else SHA="shasum -a 256"; fi

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT INT TERM

echo "update_inslib: cloning INSLIB $INSLIB_REF with KFCore"
git -c advice.detachedHead=false clone --quiet --depth 1 --branch "$INSLIB_REF" \
    --recurse-submodules --shallow-submodules "$INSLIB_URL" "$TMP/INSLIB"
KF="$TMP/INSLIB/KFCore"
[ -f "$KF/c/kalman_udu.c" ] || { echo "update_inslib: KFCore submodule missing" >&2; exit 1; }

rm -rf "$DEST"
mkdir -p "$DEST"
for f in "$TMP/INSLIB/src/"*.h "$KF/c/"*.h; do cp "$f" "$DEST/"; done
for f in "$TMP/INSLIB/src/"*.c "$KF/c/"*.c; do cp "$f" "$DEST/$(basename "$f").inc"; done
cp "$TMP/INSLIB/LICENSE" "$DEST/LICENSE.INSLIB"
cp "$KF/LICENSE"         "$DEST/LICENSE.KFCore"

{
  echo "Vendored by tools/update_inslib.sh - do not edit files in this folder."
  echo "*.c.inc files are the upstream *.c files, renamed only."
  echo
  printf 'INSLIB %s %s\n' "$INSLIB_REF" "$(git -C "$TMP/INSLIB" rev-parse HEAD)"
  printf 'KFCore %s\n' "$(git -C "$KF" rev-parse HEAD)"
  echo
  echo "sha256 (of the upstream file contents):"
  (cd "$DEST" && for f in $(ls | grep -v -e '^VERSIONS.txt$' | sort); do $SHA "$f"; done)
} > "$DEST/VERSIONS.txt"

rm -f "$WRAPDIR"/inslib_tu_*.c
for src in "$DEST"/*.c.inc; do
  base=$(basename "$src" .c.inc)
  cat > "$WRAPDIR/inslib_tu_$base.c" <<EOW
/* Generated by tools/update_inslib.sh - do not edit.
 * Compiles src/inslib/$base.c (INSLIB/KFCore, unmodified) with the build
 * configuration in trisense_inslib_config.h. SPDX-License-Identifier: AGPL-3.0-or-later */
#include "trisense_inslib_config.h"
#include "inslib/$base.c.inc"
EOW
done

n=$(ls "$WRAPDIR"/inslib_tu_*.c | wc -l | tr -d ' ')
echo "update_inslib: src/inslib populated from INSLIB $INSLIB_REF, $n wrappers written"
