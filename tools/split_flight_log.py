#!/usr/bin/env python3
"""Split a FlightLogger capture into INSLIB's dataset format.

    python3 tools/split_flight_log.py flight.log flight/

Writes imu.csv, mag.csv, baro.csv, gnss.csv, speed.csv (only those that have
data), sol.csv (the solution computed on board) and a config.yaml with the
settings TriSenseINSLIB uses on the board. Open config.yaml with INSLIB's
tools/inspostgui.py, or run tools/replay.py on it, to re-process the flight on
a PC (plots, KML, RTS smoother, different tuning).

The file formats follow INSLIB datasets/replay_format.py. All data is already
in the body FRD frame and SI units; the magnetometer is already calibrated.

Part of TriSenseINSLIB. SPDX-License-Identifier: AGPL-3.0-or-later
"""
import argparse
import os
import statistics
import sys

HEADERS = {
    "imu": "# t_us, gyr_frd_x [rad/s], gyr_frd_y [rad/s], gyr_frd_z [rad/s],"
           " acc_frd_x [m/s^2], acc_frd_y [m/s^2], acc_frd_z [m/s^2]\n",
    "mag": "# t_us, mag_frd_x [uT], mag_frd_y [uT], mag_frd_z [uT]\n",
    "baro": "# t_us, static pressure [Pa]\n",
    "speed": "# t_us, speed_mps\n",
    "gnss": "# t_us, lat_deg, lon_deg, h_m,"
            " cov_pos_ned nn,ne,nd,ee,ed,dd [m^2],"
            " vn, ve, vd [m/s],"
            " cov_vel_ned nn,ne,nd,ee,ed,dd [(m/s)^2], vel_ok,"
            " quality, gps_week, gps_tow_s, num_sv,"
            " jamming, spoofing, sig_auth, nav_auth\n",
    "sol": "# t_us, mode, roll_deg, pitch_deg, yaw_deg, height_m, vz_mps,"
           " n_m, e_m, d_m, vn_mps, ve_mps, vd_mps\n",
}
FIELDS = {"IMU": ("imu", 7), "MAG": ("mag", 4), "BARO": ("baro", 2),
          "SPEED": ("speed", 2), "GNSS": ("gnss", 11), "SOL": ("sol", 13)}

CONFIG = """\
# Generated by TriSenseINSLIB tools/split_flight_log.py from {src}.
# Matches the defaults TriSenseINS uses on the board; tune from here.
name: {name}
aiding: {aiding}
init: auto

# imu: gyr_psd / acc_psd are left at INSLIB's defaults, like on the board.
# Measure your own with INSLIB tools/allan_variance.py and set them here.

baro:
  enable: {baro}
  stddev_m: 0.6

mag:
  enable: {mag}         # mag.csv is already calibrated (setMagCalibration)
  wmm_year: 2026.5

gnss:
  enable: {gnss}
  delay_ms: {gnss_delay}     # median of the logged per-fix delays
  start_max_horizontal_pos_stddev_m: 6.0
  start_max_vertical_pos_stddev_m: 12.0
  stop_max_horizontal_pos_stddev_m: 15.0
  stop_max_vertical_pos_stddev_m: 30.0
  max_horizontal_pos_stddev_m: 15.0
  max_vertical_pos_stddev_m: 30.0

speed:
  enable: {speed}
  stddev_mps: 0.3
  delay_ms: {gnss_delay}
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("log", help="captured serial output of the FlightLogger example")
    ap.add_argument("outdir", help="folder for the dataset (created if missing)")
    args = ap.parse_args()

    os.makedirs(args.outdir, exist_ok=True)
    out = {}
    counts = {k: 0 for k in HEADERS}
    delays = []
    bad = 0

    def stream(key):
        if key not in out:
            out[key] = open(os.path.join(args.outdir, key + ".csv"), "w", newline="\n")
            out[key].write(HEADERS[key])
        return out[key]

    with open(args.log, "r", errors="replace") as f:
        for raw in f:
            raw = raw.strip()
            if not raw or raw.startswith("#"):
                continue
            parts = raw.split(",")
            spec = FIELDS.get(parts[0])
            if spec is None or len(parts) - 1 != spec[1]:
                bad += 1  # a torn line at the start/end of the capture, or other output
                continue
            key = spec[0]
            vals = parts[1:]
            try:
                [float(v) for v in vals]
            except ValueError:
                bad += 1
                continue
            if key == "gnss":
                t, lat, lon, h, nn, ne, nd, ee, ed, dd, delay = vals
                delays.append(float(delay))
                vals = [t, lat, lon, h, nn, ne, nd, ee, ed, dd,
                        "0", "0", "0", "0", "0", "0", "0", "0", "0",  # no NED velocity
                        "0", "5", "0", "0", "0", "0", "0", "0", "0"]  # vel_ok, single fix
            stream(key).write(",".join(vals) + "\n")
            counts[key] += 1

    for fh in out.values():
        fh.close()

    if counts["imu"] == 0:
        sys.exit("no IMU lines found - is this a FlightLogger capture?")

    gnss_delay = int(round(statistics.median(delays))) if delays else 0
    name = os.path.basename(os.path.normpath(args.outdir))
    with open(os.path.join(args.outdir, "config.yaml"), "w", newline="\n") as f:
        f.write(CONFIG.format(src=os.path.basename(args.log), name=name,
                              aiding="gnss" if counts["gnss"] else "none",
                              baro=int(counts["baro"] > 0), mag=int(counts["mag"] > 0),
                              gnss=int(counts["gnss"] > 0), speed=int(counts["speed"] > 0),
                              gnss_delay=gnss_delay))

    for k, n in counts.items():
        if n:
            print(f"{k + '.csv':10s} {n:8d} rows")
    if bad:
        print(f"skipped {bad} malformed line(s)")
    print(f"config.yaml written (gnss delay_ms {gnss_delay})")


if __name__ == "__main__":
    main()
